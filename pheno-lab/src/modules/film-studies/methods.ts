export function normalizeMethod(text: string) {
  return text
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\s‐‑–—_-]+/g, "");
}
export function searchMethods(query: string) {
  const words = query.trim().split(/\s+/).map(normalizeMethod);
  return methods.filter((m) => {
    const label = normalizeMethod([m.code, m.en, m.zh, m.aliases].join(" "));
    return words.every((word) => label.includes(word));
  });
}
